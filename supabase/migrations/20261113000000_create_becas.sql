create table if not exists public."Becas" (
    id bigint generated by default as identity primary key,
    participante_id bigint not null references public."Participantes"(id) on delete cascade,
    motivo text not null check (length(btrim(motivo)) > 0),
    asignacion date not null default current_date,
    inicio date not null,
    termino date not null,
    estado text not null default 'Activa' check (estado in ('Activa', 'Revocada')),
    motivo_revocacion text,
    fecha_revocacion date,
    created_at timestamptz not null default now(),
    constraint becas_periodo_valido check (termino > inicio)
);

create index if not exists becas_participante_id_id_idx
    on public."Becas" (participante_id, id desc);

alter table public."Becas" enable row level security;

grant select, insert, update on table public."Becas" to authenticated;

do $$
declare
    becas_sequence text;
begin
    becas_sequence := pg_get_serial_sequence('public."Becas"', 'id');
    if becas_sequence is not null then
        execute format('grant usage, select on sequence %s to authenticated', becas_sequence);
    end if;
end
$$;

drop policy if exists becas_authenticated_select on public."Becas";
create policy becas_authenticated_select
    on public."Becas" for select to authenticated using (true);

drop policy if exists becas_authenticated_insert on public."Becas";
create policy becas_authenticated_insert
    on public."Becas" for insert to authenticated with check (true);

drop policy if exists becas_authenticated_update on public."Becas";
create policy becas_authenticated_update
    on public."Becas" for update to authenticated using (true) with check (true);
